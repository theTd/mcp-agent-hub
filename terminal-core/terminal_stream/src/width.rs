/// `wcwidth(char)`: 1 for ordinary text, 2 for wide cells, 0 for zero-width, -1 for controls.
pub fn char_width(c: char) -> i8 {
    let cp = c as u32;
    match WIDTH_RANGES.binary_search_by(|&(first, last, _)| {
        if cp < first {
            std::cmp::Ordering::Greater
        } else if cp > last {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(index) => WIDTH_RANGES[index].2,
        Err(_) => 1,
    }
}

/// `unicodedata.combining(char) != 0`.
pub fn is_combining(c: char) -> bool {
    let cp = c as u32;
    COMBINING_RANGES
        .binary_search_by(|&(first, last)| {
            if cp < first {
                std::cmp::Ordering::Greater
            } else if cp > last {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn widths_match_the_oracle_at_the_edges() {
        assert_eq!(char_width('A'), 1);
        assert_eq!(char_width('中'), 2);
        assert_eq!(char_width('\u{1F600}'), 2);
        assert_eq!(char_width('\u{1F1E6}'), 2, "regional indicator");
        assert_eq!(char_width('\u{0301}'), 0, "combining acute");
        assert_eq!(char_width('\u{200D}'), 0, "ZWJ");
        assert_eq!(char_width('\u{2764}'), 1, "heavy black heart is narrow");
        assert_eq!(char_width('\u{7F}'), -1);
        assert!(is_combining('\u{0301}'));
        assert!(!is_combining('\u{200D}'), "ZWJ has combining class 0");
    }
}
